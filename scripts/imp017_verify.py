def failure_detail(exc, stage):
    """Offline classification; no exception strings, command args or raw output escape.

    Namespace-start detail comes only from the probe's bounded offline bwrap
    classifier. AppArmor/seccomp labels apply only to explicit Docker launch
    errors, not guesses about a failed bwrap invocation.
    """
    if isinstance(exc, subprocess.CalledProcessError):
        if stage == "whole-job-deadline-restart":
            return "deadline-workflow-failure", "verifier"
        if stage == "representative-channel-workflow":
            # A failed exec is not evidence of a Docker or parser fault. The
            # separate strict projection below uses this same captured result.
            return "client-workflow-failure", "verifier"
        if stage == "containment":
            output = exc.stdout
            if isinstance(output, bytes) and len(output) <= 256:
                try:
                    prefix, category, step = output.decode("ascii").strip().split(":")
                except (UnicodeError, ValueError):
                    pass
                else:
                    if (prefix + ":" == FAILURE_PREFIX and category in FAILURE_CATEGORIES
                            and step in PROBE_STEPS):
                        return category, step
            if exc.returncode == 125:
                diagnostics = exc.stderr
                if isinstance(diagnostics, bytes):
                    diagnostics = diagnostics[:8192].lower()
                    if b"apparmor" in diagnostics:
                        return "apparmor-runtime", "container-start"
                    if b"seccomp" in diagnostics:
                        return "seccomp-runtime", "container-start"
                return "container-runtime", "container-start"
            return "probe-runtime", "probe-launch"
        return "container-runtime", "verifier"
    if isinstance(exc, subprocess.TimeoutExpired):
        return "runtime-timeout", "probe-launch" if stage == "containment" else "verifier"
    if isinstance(exc, FileNotFoundError):
        return "runtime-unavailable", "verifier"
    if isinstance(exc, AssertionError):
        return "harness-assertion", "probe-report" if stage == "containment" else "verifier"
    return "runtime-failure", "verifier"


def docker(args, **kwargs):
    # Bounded retained output; errors never print raw Docker/parser data.
    return subprocess.run(args, check=True, stdout=subprocess.PIPE, stderr=subprocess.PIPE,
                          timeout=kwargs.pop("timeout", 120), **kwargs).stdout


def archive():
    output = io.BytesIO()
    files = [(ROOT / "api/app/pdf_protocol.py", "api/app/pdf_protocol.py"),
             (ROOT / "api/app/pdf_extractor.py", "api/app/pdf_extractor.py"),
             (ROOT / "scripts/imp017_fixtures.py", "imp017_fixtures.py")]
    with tarfile.open(fileobj=output, mode="w") as tar:
        for source, name in files:
            data = source.read_bytes()
            info = tarfile.TarInfo(name)
            info.size = len(data)
            info.mode = 0o444
            tar.addfile(info, io.BytesIO(data))
        # One valid PDF; qpdf encryption occurs later only inside the image.
        from imp017_fixtures import text_pdf
        data = text_pdf()
        info = tarfile.TarInfo("valid.pdf")
        info.size, info.mode = len(data), 0o444
        tar.addfile(info, io.BytesIO(data))
    return output.getvalue()


def old_socket_record(output):
    """Internal identity only; no path/IDs/raw captured output in reports."""
    if type(output) is not bytes or len(output) > 128:
        raise AssertionError
    try:
        identity = json.loads(output)
    except (ValueError, UnicodeError, RecursionError):
        raise AssertionError from None
    assert (type(identity) is list and len(identity) == 2
        and all(type(number) is int and 0 <= number < 2**64 for number in identity)
        and identity[1] > 0)
    canonical = json.dumps(identity, separators=(",", ":"))
    assert output == (canonical + "\n").encode("ascii")
    return canonical


