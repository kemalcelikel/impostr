import {
  applyNodeChanges,
  MarkerType,
  type Edge,
  type Node,
  type NodeChange,
  type Viewport,
} from "@xyflow/react";
import { sampleBoards, sampleCards, sampleHierarchy, sampleLayouts } from "./canvasSeeds";
import type { SampleCardContent } from "./canvasSeeds";

export const MIN_CANVAS_ZOOM = 0.25;
export const MAX_CANVAS_ZOOM = 1.5;
export const CARD_MOVE_STEP = 20;
export type CanvasNode = Node<{ content: SampleCardContent }, "sampleCard">;
export type CanvasBoardState = { nodes: CanvasNode[]; viewport: Viewport };
export type CanvasState = { activeBoardId: string; boards: Record<string, CanvasBoardState> };
export type CanvasUpdate = (current: CanvasState) => CanvasState;

export function createCanvasState(): CanvasState {
  return {
    activeBoardId: sampleBoards[0].id,
    boards: Object.fromEntries(
      sampleBoards.map((board) => [
        board.id,
        {
          nodes: board.cardIds.map((id) => ({
            id,
            type: "sampleCard" as const,
            data: { content: sampleCards[id] },
            position: { ...sampleLayouts[board.id].positions[id] },
            dragHandle: ".canvas-card-header",
            deletable: false,
            connectable: false,
            focusable: false,
            selected: false,
          })),
          viewport: { ...sampleLayouts[board.id].viewport },
        },
      ]),
    ),
  };
}

export function canvasEdges(boardId: string): Edge[] {
  return (sampleHierarchy[boardId] ?? []).map(({ parent, child }) => ({
    id: `${parent}:${child}`,
    source: parent,
    target: child,
    type: "smoothstep",
    deletable: false,
    selectable: false,
    reconnectable: false,
    focusable: false,
    markerEnd: { type: MarkerType.ArrowClosed, color: "#8ee2aa" },
    style: { stroke: "#8ee2aa", strokeWidth: 1.5 },
  }));
}

export function switchCanvasBoard(state: CanvasState, boardId: string): CanvasState {
  return state.boards[boardId] && boardId !== state.activeBoardId
    ? { ...state, activeBoardId: boardId }
    : state;
}

export function updateCanvasBoard(
  state: CanvasState,
  boardId: string,
  update: (board: CanvasBoardState) => CanvasBoardState,
): CanvasState {
  const board = state.boards[boardId];
  if (!board) return state;
  const next = update(board);
  return next === board ? state : { ...state, boards: { ...state.boards, [boardId]: next } };
}

// React Flow owns measurement, drag and selection events, but never topology or
// content. Ignore remove/add/replace even if a library callback supplies them.
export function changeCanvasNodes(
  board: CanvasBoardState,
  changes: NodeChange<CanvasNode>[],
): CanvasBoardState {
  const allowed = changes.filter(
    (change) =>
      (change.type === "position" &&
        (!change.position ||
          (Number.isFinite(change.position.x) && Number.isFinite(change.position.y)))) ||
      change.type === "select" ||
      (change.type === "dimensions" &&
        (!change.dimensions ||
          (Number.isFinite(change.dimensions.width) &&
            Number.isFinite(change.dimensions.height) &&
            change.dimensions.width > 0 &&
            change.dimensions.height > 0))),
  );
  if (!allowed.length) return board;
  const nodes = applyNodeChanges(allowed, board.nodes);
  // Only one selected card, including events generated by modified clicks.
  const selected = allowed
    .filter((change) => change.type === "select")
    .reverse()
    .find((change) => change.selected && nodes.some((node) => node.id === change.id));
  return {
    ...board,
    nodes: selected ? nodes.map((node) => ({ ...node, selected: node.id === selected.id })) : nodes,
  };
}

export function selectCanvasCard(board: CanvasBoardState, cardId: string): CanvasBoardState {
  if (cardId && !board.nodes.some((node) => node.id === cardId)) return board;
  return {
    ...board,
    nodes: board.nodes.map((node) => ({ ...node, selected: node.id === cardId })),
  };
}

export function moveCanvasCard(board: CanvasBoardState, dx: number, dy: number): CanvasBoardState {
  const selected = board.nodes.find((node) => node.selected);
  if (!selected || !Number.isFinite(dx) || !Number.isFinite(dy)) return board;
  return changeCanvasNodes(board, [
    {
      type: "position",
      id: selected.id,
      position: { x: selected.position.x + dx, y: selected.position.y + dy },
    },
  ]);
}

export function changeCanvasViewport(
  board: CanvasBoardState,
  viewport: Viewport,
): CanvasBoardState {
  if (![viewport.x, viewport.y, viewport.zoom].every(Number.isFinite)) return board;
  const next = {
    ...viewport,
    zoom: Math.min(MAX_CANVAS_ZOOM, Math.max(MIN_CANVAS_ZOOM, viewport.zoom)),
  };
  return next.x === board.viewport.x &&
    next.y === board.viewport.y &&
    next.zoom === board.viewport.zoom
    ? board
    : { ...board, viewport: next };
}
